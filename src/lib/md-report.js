/**
 * IssueReady Markdown audit report — PURE module (no Forge imports,
 * unit-testable). Mirrors src/lib/csv.js: one pure function over the
 * scoreProject report, no network, no dates from the environment except
 * the caller-supplied `exportedAt` (so tests are deterministic).
 *
 * Sections: project name, summary (average, grade, verdict + grade
 * distribution, fixable findings, duplicates), Top 5 priority fixes,
 * failures by dimension (count per dimension, top finding codes).
 */

export function toMarkdown(report, opts = {}) {
  const projectKey = opts.projectKey || 'project';
  const exportedAt = opts.exportedAt || new Date().toISOString();
  const lines = [];

  lines.push(`# IssueReady audit report — ${projectKey}`);
  lines.push('');
  lines.push(`Exported: ${exportedAt}`);
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(`- Average score: ${report.averageScore}/100 (grade ${report.grade})`);
  lines.push(`- Issues audited: ${report.total}`);
  lines.push(`- READY: ${report.byVerdict.READY} · NEEDS_WORK: ${report.byVerdict.NEEDS_WORK} · BLOCKED: ${report.byVerdict.BLOCKED}`);
  lines.push(`- Grades — A: ${report.byGrade.A} · B: ${report.byGrade.B} · C: ${report.byGrade.C} · D: ${report.byGrade.D}`);
  lines.push(`- Fixable findings (one-click): ${report.fixableFindings}`);
  lines.push(`- Likely duplicates: ${report.likelyDuplicates}`);
  lines.push('');
  lines.push('## Top 5 priority fixes');
  lines.push('');
  const queue = report.priorityQueue || [];
  if (queue.length === 0) {
    lines.push('No issues need fixing — every audited issue is clean.');
  } else {
    queue.forEach((item, i) => {
      lines.push(`${i + 1}. **${item.key}** — ${item.severity}, ${item.score}/100 (${item.grade}, ${item.verdict}): ${item.topFinding}`);
    });
  }
  lines.push('');
  lines.push('## Failures by dimension');
  lines.push('');
  const byDimension = {};
  for (const a of report.audits || []) {
    for (const f of a.findings || []) {
      byDimension[f.dimension] = byDimension[f.dimension] || { count: 0, codes: {} };
      byDimension[f.dimension].count++;
      byDimension[f.dimension].codes[f.code] =
        (byDimension[f.dimension].codes[f.code] || 0) + 1;
    }
  }
  const dims = Object.entries(byDimension).sort((a, b) => b[1].count - a[1].count);
  if (dims.length === 0) {
    lines.push('No failed checks.');
  } else {
    for (const [dimension, data] of dims) {
      lines.push(`- **${dimension}** — ${data.count} failed check(s)`);
      const codes = Object.entries(data.codes).sort((a, b) => b[1] - a[1]);
      for (const [code, count] of codes) {
        lines.push(`  - ${code}: ${count}`);
      }
    }
  }
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('Generated by IssueReady (Codegeist 2026). Scores are deterministic and reproducible from the audit rules.');
  return `${lines.join('\n')}\n`;
}
